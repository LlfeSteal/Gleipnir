// Command seed writes Gleipnir's demo dataset (package dataset, the one the fake GitLab
// serves) into a real GitLab Premium/Ultimate instance, under an existing group, so that the
// whole stack and its end-to-end tests run against a real environment.
//
//	SEED_URL=https://gitlab.example.com SEED_TOKEN=… SEED_GROUP=demo/gleipnir go run ./cmd/seed [-apply]
//
// Without -apply it only reads and prints what it would do. It is idempotent: a second run
// creates nothing, and moves the iterations and epic dates around today. It never deletes.
// SEED_TOKEN needs the api scope (write); admin rights also create the demo users. It is read
// from the environment only, and never printed.
package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"net"
	"net/url"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"

	"gitlab-mock/dataset"
)

// now places the dataset; a variable for the tests.
var now = time.Now

func main() {
	os.Exit(serve(os.Args[1:], os.Getenv, os.Stdout, os.Stderr))
}

// serve runs the seeder until done or interrupted; it returns the process exit code.
func serve(args []string, getenv func(string) string, out, errOut io.Writer) int {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, args, getenv, out); err != nil {
		fmt.Fprintln(errOut, "seed:", err)
		return 1
	}
	return 0
}

func run(ctx context.Context, args []string, getenv func(string) string, out io.Writer) error {
	flags := flag.NewFlagSet("seed", flag.ContinueOnError)
	flags.SetOutput(out)
	apply := flags.Bool("apply", false, "write to GitLab (default: dry-run, reads only)")
	insecure := flags.Bool("insecure-http", false, "allow a plain http SEED_URL outside loopback (the token travels in clear)")
	cadence := flags.String("cadence", "manual", "manual (titled iterations with a holiday gap) or auto (iterations generated by GitLab)")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *cadence != "manual" && *cadence != "auto" {
		return fmt.Errorf("-cadence %q: use manual or auto", *cadence)
	}

	base := strings.TrimRight(strings.TrimSpace(getenv("SEED_URL")), "/")
	token := strings.TrimSpace(getenv("SEED_TOKEN"))
	group := strings.Trim(strings.TrimSpace(getenv("SEED_GROUP")), "/")
	u, err := url.Parse(base)
	switch {
	case base == "":
		return fmt.Errorf("SEED_URL is required: the GitLab instance to fill (e.g. https://gitlab.example.com)")
	case err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "":
		return fmt.Errorf("SEED_URL %q is not a valid http(s) URL", base)
	case u.Scheme == "http" && !loopback(u.Hostname()) && !*insecure:
		return fmt.Errorf("SEED_URL is plain http: the write token would travel in clear; use https, or -insecure-http on a trusted network")
	case token == "":
		return fmt.Errorf("SEED_TOKEN is required: a token with the api scope (write), from the environment only")
	case group == "":
		return fmt.Errorf("SEED_GROUP is required: the full path of an existing group to fill (e.g. demo/gleipnir)")
	}

	if *apply {
		fmt.Fprintf(out, "writing the demo dataset to %s, group %s\n", base, group)
	} else {
		fmt.Fprintln(out, "dry-run: reading only, nothing is written (add -apply to write)")
	}
	s := &seeder{
		c: newClient(base, token), apply: *apply, auto: *cadence == "auto",
		root: group, ds: dataset.New(now()), out: out,
	}
	return s.run(ctx)
}

func loopback(host string) bool {
	if host == "localhost" {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}
